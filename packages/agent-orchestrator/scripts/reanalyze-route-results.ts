// packages/agent-orchestrator/scripts/reanalyze-route-results.ts
//
// Recompute item-level and confusion-matrix analysis over already-paid route-eval results.
// Reads only; writes a single derived markdown report. The result JSONs are hashed evidence and
// are never modified — see results-manifest.test.ts.
//
//   pnpm --filter @buildos/agent-orchestrator reanalyze:routes
//
// Output: src/testing/harness/results/analysis/ROUTE_REANALYSIS.md
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
	analyzeRouteItems,
	buildRouteConfusionMatrix,
	maxReachableCallScore,
	ROUTE_LABELS,
	type ObservedRoute
} from '../src/testing/harness/route-analysis';
import type { PhaseARouteEvalReport } from '../src/testing/harness/route-eval-report';

const resultsDir = fileURLToPath(new URL('../src/testing/harness/results/', import.meta.url));
const analysisDir = `${resultsDir}analysis/`;

/** The frozen A1 bound, for context only. This script never re-decides anything. */
const ROUTE_BOUND = 65;

function loadReports(): { file: string; report: PhaseARouteEvalReport }[] {
	return readdirSync(resultsDir)
		.filter((name) => name.startsWith('route-eval-') && name.endsWith('.json'))
		.sort()
		.map((file) => ({
			file,
			report: JSON.parse(
				readFileSync(`${resultsDir}${file}`, 'utf8')
			) as PhaseARouteEvalReport
		}));
}

function confusionTable(report: PhaseARouteEvalReport): string {
	const { matrix } = buildRouteConfusionMatrix(report.runs);
	const columns: ObservedRoute[] = [...ROUTE_LABELS, 'null'];
	const header = `| expected \\ observed | ${columns.join(' | ')} |`;
	const divider = `| --- | ${columns.map(() => '---:').join(' | ')} |`;
	const rows = ROUTE_LABELS.map((expected) => {
		const cells = columns.map((observed) => {
			const count = matrix[expected][observed];
			return count === 0 ? '·' : observed === expected ? `**${count}**` : String(count);
		});
		return `| ${expected} | ${cells.join(' | ')} |`;
	});
	return [header, divider, ...rows].join('\n');
}

function itemTable(report: PhaseARouteEvalReport): string {
	const { items } = analyzeRouteItems(report.runs);
	const rows = items.map((item) => {
		const flags = [
			item.passPowK ? 'pass^k' : '',
			!item.passAtK ? '**systematic failure**' : '',
			item.passAtK && !item.passPowK ? 'flaky' : ''
		]
			.filter(Boolean)
			.join(', ');
		return `| ${item.scenarioId} | ${item.expectedRoute} | ${item.correctCount}/${item.runCount} | ${item.modalRoute ?? '—'} (${item.modalCount}) | ${flags || '—'} |`;
	});
	return [
		'| scenario | expected | correct | modal answer | |',
		'| --- | --- | ---: | --- | --- |',
		...rows
	].join('\n');
}

function section(file: string, report: PhaseARouteEvalReport): string {
	const items = analyzeRouteItems(report.runs);
	const confusion = buildRouteConfusionMatrix(report.runs);
	const overall = report.summary.overall;
	const runsPerScenario = items.items[0]?.runCount ?? 0;
	const reachable = maxReachableCallScore({
		scenarioCount: items.itemCount,
		runsPerScenario,
		systematicFailureCount: items.systematicFailureScenarioIds.length
	});

	return `## ${file}

\`${report.corpus_version}\` · prompt \`${report.prompt_version}\` · ${report.routing_strategy} · pin \`${report.model_pin}\`

| measure | value |
| --- | --- |
| Call accuracy (as reported) | ${overall.routeMatchCount}/${overall.scoredRunCount} (${(overall.routeAccuracy * 100).toFixed(1)}%) |
| **Item accuracy (majority answer)** | **${items.majorityCorrectCount}/${items.itemCount}** |
| pass@k (correct at least once) | ${items.passAtKCount}/${items.itemCount} |
| **pass^k (correct on every run)** | **${items.passPowKCount}/${items.itemCount}** |
| Mean self-consistency | ${(items.meanSelfConsistency * 100).toFixed(1)}% |
| Systematically failing scenarios | ${items.systematicFailureScenarioIds.join(', ') || 'none'} |
| Max call score still reachable | ${reachable}/${items.itemCount * runsPerScenario}${reachable < ROUTE_BOUND ? ` — **below the ${ROUTE_BOUND} bound**` : ''} |

### Confusion matrix

${confusionTable(report)}

${
	confusion.confusions.length > 0
		? `Errors by boundary: ${confusion.confusions
				.map((entry) => `${entry.expected}→${entry.observed} (${entry.count})`)
				.join(', ')}.`
		: 'No errors.'
}

### Per-item

${itemTable(report)}
`;
}

const reports = loadReports();
const body = reports.map(({ file, report }) => section(file, report)).join('\n---\n\n');

const output = `<!-- GENERATED by scripts/reanalyze-route-results.ts — do not edit by hand. -->

# Route eval reanalysis

Derived from the hashed result artifacts in \`../\`. No model calls; regenerate with
\`pnpm --filter @buildos/agent-orchestrator reanalyze:routes\`.

**Why this file exists.** The reported \`routeAccuracy\` is a micro-average over
scenarios x replicates. When replicates are near-deterministic, that denominator overstates the
independent sample size and hides whether a miss is broad mediocrity or one systematically failing
item. Item accuracy, pass^k, and the confusion matrix answer those questions from the same data.

Terminology: **pass@k** = correct at least once across k trials (optimistic). **pass^k** = correct
on every trial (reliability). A production router is judged on pass^k.

---

${body}`;

mkdirSync(analysisDir, { recursive: true });
writeFileSync(`${analysisDir}ROUTE_REANALYSIS.md`, output);
console.log(
	`Wrote ${analysisDir}ROUTE_REANALYSIS.md from ${reports.length} report(s); no artifact modified.`
);
