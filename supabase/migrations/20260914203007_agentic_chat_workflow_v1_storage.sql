-- Byte-identical to canonicalizeAgenticChatJson for the fixed ASCII-keyed request
-- and history objects built below: code-unit key order, no insignificant space,
-- JSON.stringify string escaping. Only integer numbers occur in hashed values.
CREATE OR REPLACE FUNCTION public.agentic_chat_canonical_json_v1(p_value jsonb)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, public
AS $$
BEGIN
	RETURN CASE jsonb_typeof(p_value)
		WHEN 'object' THEN '{' || COALESCE((
			SELECT string_agg(
				to_jsonb(members.key)::text || ':'
					|| public.agentic_chat_canonical_json_v1(members.value),
				',' ORDER BY members.key COLLATE "C"
			)
			FROM jsonb_each(p_value) AS members(key, value)
		), '') || '}'
		WHEN 'array' THEN '[' || COALESCE((
			SELECT string_agg(
				public.agentic_chat_canonical_json_v1(items.value),
				',' ORDER BY items.position
			)
			FROM jsonb_array_elements(p_value) WITH ORDINALITY AS items(value, position)
		), '') || ']'
		ELSE p_value::text
	END;
END;
$$;

CREATE OR REPLACE FUNCTION public.agentic_chat_sha256_hex_v1(p_value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog
AS $$
	SELECT encode(sha256(convert_to(p_value, 'UTF8')), 'hex')
$$;

-- Mirrors normalizeAgenticChatText: CR/CRLF to LF, NFC, then JavaScript trim().
CREATE OR REPLACE FUNCTION public.agentic_chat_normalize_text_v1(p_value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog
AS $$
	SELECT regexp_replace(
		normalize(regexp_replace(p_value, E'\r\n?', E'\n', 'g'), NFC),
		'^[\u0009-\u000d\u0020\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+|[\u0009-\u000d\u0020\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+$',
		'',
		'g'
	)
$$;

