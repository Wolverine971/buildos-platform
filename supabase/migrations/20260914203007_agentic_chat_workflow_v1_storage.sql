-- Workflow checkpoints and their progress event commit in one transaction and
-- allocate exactly one durable sequence through the existing semantic writer.
CREATE OR REPLACE FUNCTION public.agentic_chat_workflow_publish_v1(
	p_turn_run_id uuid,
	p_queue_job_id uuid,
	p_processing_token uuid,
	p_execution_generation integer,
	p_transition_id uuid,
	p_phase text,
	p_projection jsonb,
	p_event_payload jsonb,
	p_assistant_text text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SET search_path = pg_catalog, public
AS $$
DECLARE
	v_stream_text text;
	v_receipt jsonb;
BEGIN
	IF p_transition_id IS NULL
		OR jsonb_typeof(COALESCE(p_projection, 'null'::jsonb)) <> 'object'
		OR jsonb_typeof(COALESCE(p_projection->'workflow', 'null'::jsonb)) <> 'object'
		OR p_projection#>>'{workflow,version}' IS DISTINCT FROM 'agentic_chat_workflow_projection_v1'
		OR p_projection#>>'{workflow,phase}' IS DISTINCT FROM p_phase
		OR jsonb_typeof(COALESCE(p_event_payload, 'null'::jsonb)) <> 'object'
		OR p_event_payload->>'type' IS DISTINCT FROM 'workflow_progress'
		OR p_event_payload#>>'{workflow,version}' IS DISTINCT FROM 'agentic_chat_workflow_projection_v1'
		OR p_event_payload#>>'{workflow,phase}' IS DISTINCT FROM p_phase THEN
		RAISE EXCEPTION 'agentic_chat_workflow_invalid_progress_projection';
	END IF;

	SELECT streams.assistant_text
	INTO v_stream_text
	FROM public.chat_turn_stream_state streams
	WHERE streams.turn_run_id = p_turn_run_id;

	v_receipt := public.persist_agentic_chat_semantic_event(
		p_turn_run_id,
		p_queue_job_id,
		p_processing_token,
		p_execution_generation,
		p_transition_id,
		COALESCE(p_assistant_text, v_stream_text, ''),
		'llm',
		'workflow_progress',
		p_projection,
		p_event_payload
	);
	IF v_receipt->>'outcome' IS DISTINCT FROM 'persisted'
		AND v_receipt->>'outcome' IS DISTINCT FROM 'already_persisted' THEN
		RAISE EXCEPTION 'agentic_chat_workflow_progress_not_durable';
	END IF;
	RETURN v_receipt;
END;
$$;

