-- Budget exposure: reserved-but-unknown work counts at its reservation; settled
-- work counts at its actual charge, including any overrun.
CREATE OR REPLACE FUNCTION public.agentic_chat_workflow_exposure_micro_usd_v1(p_turn_run_id uuid)
RETURNS bigint
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public
AS $$
	SELECT COALESCE(sum(
		CASE
			WHEN dispatches.state IN ('reserved', 'dispatching', 'uncertain')
				THEN dispatches.reserved_micro_usd
			WHEN dispatches.state = 'settled' THEN dispatches.actual_micro_usd
			ELSE 0
		END
	), 0)::bigint
	FROM public.chat_turn_workflow_dispatches dispatches
	WHERE dispatches.turn_run_id = p_turn_run_id
$$;

CREATE OR REPLACE FUNCTION public.enforce_agentic_chat_workflow_run_transition_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
	v_phases constant text[] := ARRAY['preparing', 'assessing', 'executing', 'synthesizing', 'finished'];
BEGIN
	IF ROW(NEW.turn_run_id, NEW.session_id, NEW.user_id, NEW.request_artifact_id, NEW.project_id,
			NEW.workflow_version, NEW.policy, NEW.policy_ref, NEW.request_hash,
			NEW.max_spend_micro_usd, NEW.synthesis_headroom_micro_usd, NEW.max_physical_dispatches,
			NEW.max_step_attempts, NEW.whole_run_lifetime_ms, NEW.created_at)
		IS DISTINCT FROM ROW(OLD.turn_run_id, OLD.session_id, OLD.user_id, OLD.request_artifact_id,
			OLD.project_id, OLD.workflow_version, OLD.policy, OLD.policy_ref, OLD.request_hash,
			OLD.max_spend_micro_usd, OLD.synthesis_headroom_micro_usd, OLD.max_physical_dispatches,
			OLD.max_step_attempts, OLD.whole_run_lifetime_ms, OLD.created_at)
		OR (OLD.deadline_at IS NOT NULL AND NEW.deadline_at IS DISTINCT FROM OLD.deadline_at)
		OR (OLD.first_execution_started_at IS NOT NULL
			AND NEW.first_execution_started_at IS DISTINCT FROM OLD.first_execution_started_at)
		OR NEW.recovery_count < OLD.recovery_count
		OR (OLD.context_id IS NOT NULL AND ROW(NEW.context_id, NEW.preparation_version,
				NEW.context_identity, NEW.evidence_versions, NEW.context_payload, NEW.context_hash,
				NEW.context_bytes, NEW.context_accepted_at, NEW.context_accepted_generation)
			IS DISTINCT FROM ROW(OLD.context_id, OLD.preparation_version, OLD.context_identity,
				OLD.evidence_versions, OLD.context_payload, OLD.context_hash, OLD.context_bytes,
				OLD.context_accepted_at, OLD.context_accepted_generation))
		OR (OLD.plan_hash IS NOT NULL AND ROW(NEW.plan_version, NEW.plan, NEW.plan_hash,
				NEW.plan_installed_at, NEW.plan_installed_generation)
			IS DISTINCT FROM ROW(OLD.plan_version, OLD.plan, OLD.plan_hash, OLD.plan_installed_at,
				OLD.plan_installed_generation))
		OR (OLD.answer_id IS NOT NULL AND ROW(NEW.answer_id, NEW.answer_editor_step_attempt_id)
			IS DISTINCT FROM ROW(OLD.answer_id, OLD.answer_editor_step_attempt_id))
		OR left(NEW.answer_text, char_length(OLD.answer_text)) IS DISTINCT FROM OLD.answer_text
		OR (OLD.synthesis_status = 'accepted' AND ROW(NEW.synthesis_status, NEW.synthesis_quality,
				NEW.synthesis_accepted_at, NEW.answer_text, NEW.answer_text_sha256)
			IS DISTINCT FROM ROW(OLD.synthesis_status, OLD.synthesis_quality,
				OLD.synthesis_accepted_at, OLD.answer_text, OLD.answer_text_sha256))
		OR (OLD.phase = 'finished' AND ROW(NEW.phase, NEW.terminal_outcome, NEW.finished_at)
			IS DISTINCT FROM ROW(OLD.phase, OLD.terminal_outcome, OLD.finished_at))
		OR array_position(v_phases, NEW.phase) < array_position(v_phases, OLD.phase) THEN
		RAISE EXCEPTION 'agentic_chat_workflow_run_transition_invalid';
	END IF;
	NEW.updated_at := GREATEST(clock_timestamp(), OLD.updated_at);
	RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.enforce_agentic_chat_workflow_step_transition_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
	IF ROW(NEW.turn_run_id, NEW.session_id, NEW.user_id, NEW.plan_version, NEW.step_key,
			NEW.capability, NEW.depends_on, NEW.assignment, NEW.created_at)
		IS DISTINCT FROM ROW(OLD.turn_run_id, OLD.session_id, OLD.user_id, OLD.plan_version,
			OLD.step_key, OLD.capability, OLD.depends_on, OLD.assignment, OLD.created_at)
		OR (OLD.status IN ('accepted', 'failed', 'skipped') AND ROW(NEW.status, NEW.quality,
				NEW.result, NEW.result_hash, NEW.result_bytes, NEW.accepted_attempt_id,
				NEW.accepted_at, NEW.failure_code, NEW.finished_at, NEW.attempts_used, NEW.attempt_ids)
			IS DISTINCT FROM ROW(OLD.status, OLD.quality, OLD.result, OLD.result_hash,
				OLD.result_bytes, OLD.accepted_attempt_id, OLD.accepted_at, OLD.failure_code,
				OLD.finished_at, OLD.attempts_used, OLD.attempt_ids))
		OR NEW.attempts_used < OLD.attempts_used
		OR NEW.attempt_ids[1:cardinality(OLD.attempt_ids)] IS DISTINCT FROM OLD.attempt_ids
		OR NOT (
			NEW.status = OLD.status
			OR (OLD.status = 'pending' AND NEW.status IN ('claimed', 'failed', 'skipped'))
			OR (OLD.status = 'claimed' AND NEW.status IN ('pending', 'accepted', 'failed', 'skipped'))
		) THEN
		RAISE EXCEPTION 'agentic_chat_workflow_step_transition_invalid';
	END IF;
	NEW.updated_at := GREATEST(clock_timestamp(), OLD.updated_at);
	RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.enforce_agentic_chat_workflow_dispatch_transition_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
	IF TG_OP = 'INSERT' THEN
		IF NEW.state <> 'reserved' THEN
			RAISE EXCEPTION 'agentic_chat_workflow_dispatch_must_start_reserved';
		END IF;
		RETURN NEW;
	END IF;
	IF ROW(NEW.dispatch_id, NEW.turn_run_id, NEW.session_id, NEW.user_id, NEW.step_key,
			NEW.step_attempt_id, NEW.physical_attempt, NEW.dispatch_kind, NEW.model_requested,
			NEW.pricing, NEW.serialized_request_bytes, NEW.estimated_input_tokens,
			NEW.max_output_tokens, NEW.reserved_micro_usd, NEW.settlement_token,
			NEW.reserved_generation, NEW.reserved_at, NEW.created_at)
		IS DISTINCT FROM ROW(OLD.dispatch_id, OLD.turn_run_id, OLD.session_id, OLD.user_id,
			OLD.step_key, OLD.step_attempt_id, OLD.physical_attempt, OLD.dispatch_kind,
			OLD.model_requested, OLD.pricing, OLD.serialized_request_bytes,
			OLD.estimated_input_tokens, OLD.max_output_tokens, OLD.reserved_micro_usd,
			OLD.settlement_token, OLD.reserved_generation, OLD.reserved_at, OLD.created_at)
		OR (OLD.dispatched_at IS NOT NULL AND NEW.dispatched_at IS DISTINCT FROM OLD.dispatched_at)
		OR (OLD.uncertain_at IS NOT NULL AND NEW.uncertain_at IS DISTINCT FROM OLD.uncertain_at)
		OR OLD.state IN ('settled', 'released')
		OR NOT (
			(OLD.state = 'reserved' AND NEW.state IN ('dispatching', 'released'))
			OR (OLD.state = 'dispatching' AND NEW.state IN ('settled', 'uncertain'))
			OR (OLD.state = 'uncertain' AND NEW.state IN ('settled', 'released'))
		) THEN
		RAISE EXCEPTION 'agentic_chat_workflow_dispatch_transition_invalid';
	END IF;
	NEW.updated_at := GREATEST(clock_timestamp(), OLD.updated_at);
	RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.reject_protected_agentic_chat_workflow_dispatch_delete()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
	v_status text;
	v_terminal_at timestamptz;
BEGIN
	SELECT turns.status, COALESCE(turns.terminalized_at, turns.finished_at)
	INTO v_status, v_terminal_at
	FROM public.chat_turn_runs turns
	WHERE turns.id = OLD.turn_run_id;

	IF NOT FOUND OR v_status IN ('queued', 'running') THEN
		RAISE EXCEPTION 'agentic_chat_workflow_active_dispatch_cannot_be_deleted';
	END IF;
	IF OLD.state IN ('reserved', 'dispatching', 'uncertain') THEN
		RAISE EXCEPTION 'agentic_chat_workflow_unresolved_dispatch_cannot_be_deleted';
	END IF;
	IF v_status NOT IN ('completed', 'failed', 'cancelled') OR v_terminal_at IS NULL THEN
		RAISE EXCEPTION 'agentic_chat_workflow_dispatch_terminal_turn_required';
	END IF;
	IF OLD.reconciled_at IS NOT NULL THEN
		IF clock_timestamp() < GREATEST(v_terminal_at, OLD.reconciled_at) + interval '90 days' THEN
			RAISE EXCEPTION 'agentic_chat_workflow_reconciled_dispatch_retention_not_elapsed';
		END IF;
		RETURN OLD;
	END IF;
	IF clock_timestamp() < GREATEST(v_terminal_at, OLD.settled_at) + interval '30 days' THEN
		RAISE EXCEPTION 'agentic_chat_workflow_dispatch_retention_not_elapsed';
	END IF;
	RETURN OLD;
END;
$$;

