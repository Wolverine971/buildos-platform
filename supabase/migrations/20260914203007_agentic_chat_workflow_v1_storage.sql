			)
			OR (
				artifact_version = 'agentic_chat_input_v4'
				AND prepared IS NULL
				AND request IS NOT NULL
				AND jsonb_typeof(request) = 'object'
				AND request_hash IS NOT NULL
				AND request_hash ~ '^[0-9a-f]{64}$'
				AND history_hash IS NOT NULL
				AND history_hash ~ '^[0-9a-f]{64}$'
				AND history_source = 'admission_window'
				AND source_prepared_prompt_id IS NULL
			)
		) NOT VALID,
	ADD CONSTRAINT chk_chat_turn_input_artifacts_content_bound
		CHECK (
			history_bytes >= 0
			AND history_bytes <= 262144
			AND content_bytes > 0
			AND content_bytes <= 2097152
			AND history_bytes <= content_bytes
			AND octet_length(history::text)
				+ COALESCE(octet_length(prepared::text), 0)
				+ COALESCE(octet_length(request::text), 0) <= 4194304
		) NOT VALID;

