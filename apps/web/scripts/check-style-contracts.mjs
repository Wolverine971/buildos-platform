// apps/web/scripts/check-style-contracts.mjs
import { readdir, readFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const webRoot = join(import.meta.dirname, '..');
const srcRoot = join(webRoot, 'src');
const failures = [];

async function collectFiles(directory) {
	const entries = await readdir(directory, { withFileTypes: true });
	const nested = await Promise.all(
		entries.map((entry) => {
			const path = join(directory, entry.name);
			return entry.isDirectory() ? collectFiles(path) : [path];
		})
	);
	return nested.flat();
}

function fail(file, message) {
	failures.push(`${relative(webRoot, file)}: ${message}`);
}

const sourceFiles = (await collectFiles(srcRoot)).filter((file) =>
	/\.(?:css|html|svelte|ts)$/.test(file)
);
const contents = new Map(
	await Promise.all(sourceFiles.map(async (file) => [file, await readFile(file, 'utf8')]))
);

const arbitraryFontSize = /text-\[[^\]]+\]/;
for (const [file, content] of contents) {
	if (file.endsWith('.svelte') && arbitraryFontSize.test(content)) {
		fail(
			file,
			'use the canonical Tailwind/Inkprint type scale instead of an arbitrary font size'
		);
	}
	if (file.endsWith('.svelte') && content.includes('-webkit-tap-highlight-color: transparent')) {
		fail(file, 'tap-highlight behavior is owned by app.css');
	}
	if (
		file.endsWith('.svelte') &&
		/var\(--color-(?:background|foreground|card|muted|accent|border)/.test(content)
	) {
		fail(file, 'use Inkprint semantic tokens directly instead of legacy --color-* aliases');
	}
}

const inkprintPath = join(srcRoot, 'lib/styles/inkprint.css');
const inkprint = contents.get(inkprintPath) ?? '';
if (/\.shadow-ink(?:-strong|-inner)?\s*\{/.test(inkprint)) {
	fail(
		inkprintPath,
		'shadow utilities are generated by Tailwind; keep only the shadow tokens here'
	);
}

const pwaPath = join(srcRoot, 'lib/styles/pwa.css');
const pwa = contents.get(pwaPath) ?? '';
if (/\.pwa-installed\s+(?:button|a|\.clickable):active/.test(pwa)) {
	fail(pwaPath, 'PWA CSS must not replace component-owned active transforms');
}
if (pwa.includes('color-scheme:')) {
	fail(pwaPath, 'ModeWatcher owns color-scheme resolution');
}
if (
	/\.pwa-installed::-webkit-scrollbar\s*\{[^}]*display:\s*none/s.test(pwa) ||
	/\.pwa-installed\s*\{[^}]*(?:scrollbar-width:\s*none|-ms-overflow-style:\s*none)/s.test(pwa)
) {
	fail(pwaPath, 'keep the installed-PWA page scrollbar visible as a scroll affordance');
}

const pwaEnhancementsPath = join(srcRoot, 'lib/utils/pwa-enhancements.ts');
const pwaEnhancements = contents.get(pwaEnhancementsPath) ?? '';
if (/THEME_COLORS|#[\da-f]{6}\b/i.test(pwaEnhancements)) {
	fail(pwaEnhancementsPath, 'app.html is the single source of truth for browser theme colors');
}

const layoutPath = join(srcRoot, 'routes/+layout.svelte');
const layout = contents.get(layoutPath) ?? '';
if (layout.includes('padding-left: max(0px, env(safe-area-inset-left))')) {
	fail(layoutPath, 'body/app.css is the single owner of horizontal safe-area padding');
}

const agentChatPath = join(srcRoot, 'lib/components/agent/AgentChatModal.svelte');
const agentChat = contents.get(agentChatPath) ?? '';
if (
	agentChat.includes('agent-chat-keyboard-modal') ||
	/:global\([^)]*modal-content/.test(agentChat)
) {
	fail(agentChatPath, 'use the shared Modal presentation API instead of cross-component CSS');
}

const modalPath = join(srcRoot, 'lib/components/ui/Modal.svelte');
const modal = contents.get(modalPath) ?? '';
if (!modal.includes("'flex flex-col overflow-hidden'")) {
	fail(modalPath, 'non-scrollable modal content must remain a min-height-aware flex column');
}

const explicitTransitionFiles = [
	'lib/components/ui/Button.svelte',
	'lib/components/ui/TextInput.svelte',
	'lib/components/ui/Textarea.svelte',
	'lib/components/ui/Select.svelte',
	'lib/components/ui/Modal.svelte',
	'lib/components/ui/FormModal.svelte',
	'lib/components/ui/Alert.svelte'
];
for (const relativePath of explicitTransitionFiles) {
	const file = join(srcRoot, relativePath);
	if (/(?:class=|['"])[^'"\n]*\btransition-all\b/.test(contents.get(file) ?? '')) {
		fail(file, 'shared controls must declare only the properties they animate');
	}
}

const formModalPath = join(srcRoot, 'lib/components/ui/FormModal.svelte');
const formModal = contents.get(formModalPath) ?? '';
if (!/h-11 w-11[\s\S]{0,300}aria-label="Close modal"/.test(formModal)) {
	fail(formModalPath, 'the modal dismiss action must retain its 44px touch target');
}

const alertPath = join(srcRoot, 'lib/components/ui/Alert.svelte');
const alert = contents.get(alertPath) ?? '';
if (!/h-11 w-11[\s\S]{0,300}aria-label="Close alert"/.test(alert)) {
	fail(alertPath, 'the alert dismiss action must retain its 44px touch target');
}

const briefChatPath = join(srcRoot, 'lib/components/briefs/BriefChatModal.svelte');
const briefChat = contents.get(briefChatPath) ?? '';
if (/brief-modal-container|brief-chat-root|use:portal/.test(briefChat)) {
	fail(briefChatPath, 'delegate modal stacking, gestures, focus, and scroll locking to Modal');
}

const semanticStyleFiles = [
	'lib/components/time-blocks/TimePlayCalendar.svelte',
	'lib/components/time-blocks/TimeAllocationPanel.svelte',
	'lib/components/time-blocks/TimeRangeSelector.svelte',
	'lib/components/sms/monitoring/ActiveAlertsList.svelte',
	'lib/components/sms/monitoring/DeliveryRateChart.svelte',
	'lib/components/sms/monitoring/LLMMetricsChart.svelte',
	'lib/components/sms/monitoring/MetricsSummaryCard.svelte',
	'routes/(app)/sms/monitoring/+page.svelte'
];
for (const relativePath of semanticStyleFiles) {
	const file = join(srcRoot, relativePath);
	const style = (contents.get(file) ?? '').slice((contents.get(file) ?? '').indexOf('<style'));
	if (/#[\da-f]{3,8}\b|rgba?\(/i.test(style)) {
		fail(file, 'use semantic Inkprint color/shadow tokens in component CSS');
	}
	if (relativePath.includes('time-blocks/') && style.includes(':global(.dark)')) {
		fail(file, 'Inkprint tokens own time-block light/dark resolution');
	}
}

if (failures.length > 0) {
	console.error(
		'Style contract violations:\n' + failures.map((failure) => `- ${failure}`).join('\n')
	);
	process.exitCode = 1;
} else {
	console.log('Style ownership and typography contracts are clean.');
}
